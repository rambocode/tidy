/** Stored language mode: auto (follow system) or a fixed language. */
export function langMode(): "auto" | Lang {
  const stored = localStorage.getItem("mole-lang");
  if (stored === "zh" || stored === "en") return stored;
  return "auto";
}

/** Resolve the active language: stored choice, else system locale. */
export function lang(): Lang {
  const mode = langMode();
  if (mode !== "auto") return mode;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

/** Translate a key, with optional {placeholder} substitution. {app} always
 * resolves to the product name. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let text = DICT[lang()][key] ?? DICT.en[key] ?? key;
  text = text.replaceAll("{app}", PRODUCT_NAME);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/** Switch language mode and re-render the current route. */
export function setLang(l: "auto" | Lang): void {
  if (l === "auto") localStorage.removeItem("mole-lang");
  else localStorage.setItem("mole-lang", l);
  window.dispatchEvent(new HashChangeEvent("hashchange"));
}
