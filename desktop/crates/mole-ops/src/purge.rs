/// Files whose presence marks a directory as a project root. Discovery walks
/// containers until it finds one of these (or .git), so projects can live at
/// any depth (e.g. ~/source/project/<name>) instead of only container/<name>.
const PROJECT_MARKERS: &[&str] = &[
    ".git",
    "package.json",
    "Cargo.toml",
    "pyproject.toml",
    "setup.py",
    "requirements.txt",
    "go.mod",
    "pom.xml",
    "build.gradle",
    "build.gradle.kts",
    "Gemfile",
    "composer.json",
    "Package.swift",
    "Podfile",
    "pubspec.yaml",
    "CMakeLists.txt",
    "Makefile",
    "mix.exs",
    "build.zig",
];

/// True when `dir` looks like a project root (has a marker or .sln/.csproj).
/// One read_dir instead of ~20 stat calls: discovery visits many dirs.
fn is_project(dir: &Path) -> bool {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return false;
    };
    entries.flatten().any(|e| {
        let name = e.file_name();
        let name = name.to_string_lossy();
        PROJECT_MARKERS.contains(&name.as_ref())
            || name.ends_with(".sln")
            || name.ends_with(".csproj")
    })
}

